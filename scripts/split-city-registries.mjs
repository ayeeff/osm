// Split the generated city list in two.
//
// cities.json drives osm-city-2d-data.yml, whose matrix is one job PER CITY. If
// it listed all ~900 cities, that workflow's weekly cron would schedule ~900
// per-city jobs, each re-downloading its whole country PBF. That is the exact
// cost the new per-extract workflow exists to avoid, so the two registries are
// kept apart on purpose.
//
//   cities.json                 the 5 cities the 2D pipeline serves (places,
//                               demand-streets, neighbourhoods) -- small by design
//   cities-neighborhoods.json   every city with a staged extract, for the
//                               per-extract neighbourhood sweep only
import fs from 'node:fs';

const cur = JSON.parse(fs.readFileSync('cities.json', 'utf8'));
const KEEP_2D = ['beijing', 'melbourne', 'berlin', 'amsterdam', 'hongkong'];

const small = cur.cities.filter((c) => KEEP_2D.includes(c.slug));
const rest = cur.cities.filter((c) => !KEEP_2D.includes(c.slug));

const withCount = (cities, extra) => ({
  ...cur,
  ...extra,
  count: cities.length,
  cities,
});

fs.writeFileSync('cities.json', JSON.stringify(withCount(small), null, 1));
fs.writeFileSync(
  'cities-neighborhoods.json',
  JSON.stringify(
    withCount(rest, {
      $comment:
        'Cities for osm-city-neighborhoods.yml only. Deliberately separate from ' +
        'cities.json: that file also drives osm-city-2d-data.yml, whose per-city ' +
        'matrix would otherwise schedule ~900 per-city jobs on its weekly cron. ' +
        'bbox is [minLng,minLat,maxLng,maxLat]. Generated by ' +
        'geo/site/scripts/build-osm-cities-json.mjs.',
    }),
    null,
    1
  )
);

console.log(`cities.json                -> ${small.length} cities (2D pipeline, unchanged size)`);
console.log(`cities-neighborhoods.json  -> ${rest.length} cities (per-extract sweep)`);
const extracts = new Set(rest.map((c) => c.extract));
console.log(`cities-neighborhoods.json  -> ${extracts.size} distinct extracts`);
